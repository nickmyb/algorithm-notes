// Package snippets 是题解辅助函数和数据结构的权威版本，只供复制，不供 import。
//
// 题解本体必须能原样提交到 LeetCode，而提交框只收一个文件，所以题解里用到的
// 辅助函数只能整段复制进去，不能引用这里。本目录的作用是让这些副本有一个
// 经过测试的源头，并由 check_test.go 保证副本不漂移：
//
//   - 这里每个非测试文件里的顶层函数、类型和方法都是一个 snippet，按名字识别：
//     函数 abs、类型 type MaxPQ、方法 MaxPQ.sink（接收者去掉 * 和类型参数）。
//   - leetcode/ 下任何题解定义了同名的函数、类型或方法，就视为引用了它，
//     从 func / type 关键字到结尾必须和这里逐字一致；上方的文档注释不比较，
//     各题可以写自己的说明。数据结构只用到一部分时只复制那一部分，没定义的名字不检查。
//   - 和 structures/go 同名的类型（如 TreeNode）是平台类型的替身，不算 snippet；
//     题解里的类型别名是接线，也不检查。
//   - 这里只能 import 标准库，否则复制到 LeetCode 编译不过。
//   - 每个 snippet 都要在同名 _test.go 里有测试。
//
// 文件的划分就是 make snippets 给题目分组的依据，所以：
//
//   - 文件名按用途（这组题靠什么连在一起），不按数据类型：anagram.go，
//     不要叫 strings.go，也别和标准库包同名。
//   - 每个函数只在一个文件里；有多种用途时放最一般的那个，用途变了就移动，
//     检查按函数名，移动不影响任何副本。
//   - 写法不同就是不同的函数，起不同的名字。
//
// 思路上的同类关系不靠这里表达，写在题解 README 的「同类题」里。
//
// 改 snippet 时，check_test.go 会列出所有不一致的副本，逐个同步即可。
// 包名是 snippets 而目录叫 go，和 structures/go 同理（go 是关键字）。
